  function detect() {
    var nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'zh-CN'
    var n = String(nav).toLowerCase()
    if (n.indexOf('zh') === 0) {
      if (n.indexOf('tw') > 0 || n.indexOf('hk') > 0 || n.indexOf('mo') > 0 || n.indexOf('hant') > 0) return 'zh-TW'
      return 'zh-CN'
    }
    if (n.indexOf('ja') === 0) return 'ja'
    if (n.indexOf('ko') === 0) return 'ko'
    if (n.indexOf('en') === 0) return 'en'
    return 'zh-CN'
  }

  function t(key, params) {
    var L = STR[current] || STR['zh-CN']
    var s = L[key]
    if (s == null) s = STR['zh-CN'][key] != null ? STR['zh-CN'][key] : key
    if (params) {
      for (var k in params) s = s.split('{' + k + '}').join(String(params[k]))
    }
    return s
  }

